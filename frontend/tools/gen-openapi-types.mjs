import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import crypto from "node:crypto";
import openapiTS from "openapi-typescript";

const host = process.env.KUTM_HOSTNAME || "kutm.local";
const sourceUrl = process.env.OPENAPI_URL || `https://${host}/openapi.json`;
const outFile = path.resolve("src/gen/openapi.d.ts");

const response = await fetch(sourceUrl);
if (!response.ok) {
  throw new Error(`Failed to fetch OpenAPI from ${sourceUrl}: HTTP ${response.status}`);
}

const specText = await response.text();
const specHash = crypto.createHash("sha256").update(specText).digest("hex");
const spec = JSON.parse(specText);
const generated = await openapiTS(spec);
const output = `// Generated by tools/gen-openapi-types.mjs\n// source: ${sourceUrl}\n// sha256: ${specHash}\n\n${generated}`;

await fs.mkdir(path.dirname(outFile), { recursive: true });
await fs.writeFile(outFile, output, "utf8");
console.log(`Wrote ${outFile}`);
