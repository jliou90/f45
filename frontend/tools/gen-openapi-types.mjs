import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import crypto from "node:crypto";
import openapiTS, { astToString } from "openapi-typescript";

const host = process.env.KUTM_HOSTNAME || "kutm.local";
const sourceUrl = process.env.OPENAPI_URL || `https://${host}/openapi.json`;
const sourceFile = process.env.OPENAPI_FILE || path.resolve("src/api/openapi.json");
const outFile = path.resolve("src/gen/openapi.d.ts");

async function loadSpecText() {
  if (!process.env.OPENAPI_URL) {
    const specText = await fs.readFile(sourceFile, "utf8");
    return {
      specText,
      resolvedSource: `local-file://${path.relative(process.cwd(), sourceFile).replace(/\\/g, "/")}`,
    };
  }
  try {
    const response = await fetch(sourceUrl);
    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }
    const specText = await response.text();
    return { specText, resolvedSource: sourceUrl };
  } catch {
    const specText = await fs.readFile(sourceFile, "utf8");
    return {
      specText,
      resolvedSource: `local-file://${path.relative(process.cwd(), sourceFile).replace(/\\/g, "/")}`,
    };
  }
}

const { specText, resolvedSource } = await loadSpecText();
const specHash = crypto.createHash("sha256").update(specText).digest("hex");
const spec = JSON.parse(specText);
const generated = astToString(await openapiTS(spec));
const output = `// Generated by tools/gen-openapi-types.mjs\n// source: ${resolvedSource}\n// sha256: ${specHash}\n\n${generated}`;

await fs.mkdir(path.dirname(outFile), { recursive: true });
await fs.writeFile(outFile, output, "utf8");
console.log(`Wrote ${outFile}`);
